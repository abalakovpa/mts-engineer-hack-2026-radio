def n(value, places=2):
    return f'{value:.{places}f}'.replace('.', ',')

def section(title, *parts):
    return '# '+title+'\n\n'+'\n\n'.join(parts)+'\n\n'

def coverage_table(cov):
    values={(r['scenario'],r['frequency_mhz']):r['reference_percent_2100'] for r in cov['scenarios']}
    scenarios=[('P1_n2.5','Основной расчёт, n=2,5'),('P1_n3','n=3'),
               ('P1_n3_closed_gaps','n=3, закрытые проёмы'),('P1_extra_RF_3dB','n=2,5, дополнительные потери 3 дБ'),
               ('P1_closed_gaps_geometry_uncertain_fail_RF3','n=2,5, проёмы / контур / 3 дБ'),
               ('P2_carrier23','23 дБм как мощность всей несущей')]
    return table(['Расчётный режим','B3, %','B1, %','B7, %'],
                 [[label]+[n(values[name,f]) for f in (1800,2100,2600)] for name,label in scenarios])

