def format_equipment():
    path=ROOT/'equipment/bill-of-materials.xlsx'
    workbook=load_workbook(path)
    for name in ('Статус','Исходный перечень'):
        if name in workbook.sheetnames:del workbook[name]
    sheet=workbook['Спецификация']
    assert sheet.max_row==len(SPECIFICATION)+1
    for row,(model,characteristics) in enumerate(SPECIFICATION,2):
        sheet.cell(row,2,model);sheet.cell(row,3,characteristics)
    sheet=workbook['Комплектность']
    assert sheet.max_row==len(CONDITIONS)+1
    sheet.cell(1,3,'Техническое условие')
    for row,values in enumerate(CONDITIONS,2):
        for column,value in enumerate(values,1):sheet.cell(row,column,value)
    sheet=workbook['Портовый план'];sheet.cell(1,4,'Функция соединения')
    labels={'Резерв, мощность не задана':'Резерв LTE-оператора',
            'Проект':'Соединение RF-тракта',
            'Общий выход БС принят условно':'Общий RF-выход двух GSM TRX (условие расчёта)',
            'Неукомплектовано':'Подключение нагрузки 50 Ом; изделие выбирается при комплектации'}
    for row in range(2,sheet.max_row+1):
        cell=sheet.cell(row,4)
        if cell.value in labels:cell.value=labels[cell.value]
    sheet=workbook['Размещение'];sheet.cell(1,5,'Проектная зона')
    for row in range(2,sheet.max_row+1):
        cell=sheet.cell(row,5)
        if cell.value=='Головной узел; размеры и монтажная раскладка не заданы':cell.value='Головной узел, проектная зона 104.2'
        elif cell.value=='Исследовательская позиция n=3; монтажная доступность не подтверждена':cell.value='Проектная точка антенны; доступность места установки проверяется при монтаже'
        elif cell.value=='Головной узел; общий GSM-выход условен':cell.value='Головной узел; подключение общего RF-выхода GSM'
        elif cell.value=='Подгруппа на трассе; M1/M2 показаны одной геометрической точкой':cell.value='Подгруппа на трассе; отдельные устройства M1/M2 в одной проектной зоне'
    sheet=workbook['Трассы'];sheet.cell(1,6,'Примечание')
    for row in range(2,sheet.max_row+1):
        cell=sheet.cell(row,6)
        if cell.value=='Проектная аппроксимация CAD-лотков; без запаса':cell.value='По проектной трассе лотков; без закупочного резерва'
    for sheet in workbook:
        widths={sheet.cell(1,i).column_letter:
                sheet.column_dimensions[sheet.cell(1,i).column_letter].width
                for i in range(1,sheet.max_column+1)}
        style(sheet,widths)
    workbook.save(path)
    print(f'Technical equipment workbook: {len(workbook.sheetnames)} sheets.')

if __name__=='__main__':format_equipment()
